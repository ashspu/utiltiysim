import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
import {chromium,browserOptions} from './browser-runtime.mjs';
const base=process.env.ATLAS_URL||'http://127.0.0.1:8041',out='out/civic-atlas/immersive-review';await mkdir(out,{recursive:true});
const browser=await chromium.launch(browserOptions),errors=[];
try{
 const page=await browser.newPage({viewport:{width:1600,height:1000}});page.on('pageerror',e=>errors.push(e.message));
 const before=await(await page.request.get(base+'/atlas/api/bootstrap')).json();
 await page.goto(base+'/#map');await page.waitForFunction(()=>document.body.dataset.ready==='true',null,{timeout:180000});
 const diag=()=>page.evaluate(()=>window.atlasDiagnostics());
 assert.deepEqual(await page.locator('#map-canvas').boundingBox(),{x:0,y:0,width:1600,height:1000});
 assert.equal(await page.locator('.sidebar').isVisible(),false);assert.equal(await page.locator('.topbar').isVisible(),false);
 assert.equal(await page.locator('#map-options').isVisible(),false);assert.equal(await page.locator('#property-dialog').isVisible(),false);
 await page.screenshot({path:out+'/map-1600.png'});
 const camera=(await diag()).camera;
 await page.locator('#open-navigation').click();assert.equal(await page.locator('.sidebar').isVisible(),true);
 await page.locator('#collapse-navigation').click();assert.equal(await page.evaluate(()=>document.body.dataset.navigation),'rail');
 await page.locator('#hide-navigation').click();assert.deepEqual((await diag()).camera,camera);
 await page.locator('#toggle-map-options').click();assert.equal(await page.locator('#map-options').isVisible(),true);
 await page.locator('[data-layer=water]').click();assert.match(await page.locator('#legend-text').textContent(),/topology/);
 await page.locator('[data-layer=town]').click();
 const home=before.snapshot.premises.find(p=>p.premiseType==='residential');
 await page.locator('#map-search').fill(home.id);await page.locator('#search-results [data-property]').first().click();
 await page.waitForFunction(id=>window.atlasDiagnostics().selectedId===id,home.id);
 await page.locator('#close-map-options').click();
 assert.equal(await page.locator('#property-dialog').isVisible(),false);
 await page.locator('#view-property').click();await page.locator('.reading-value').waitFor();
 assert.ok((await page.locator('#inspector-content').textContent()).includes(home.id));
 await page.locator('#close-property-dialog').click();assert.equal(await page.locator('#property-dialog').isVisible(),false);
 await page.locator('#clear-map-selection').click();assert.equal(await page.locator('#map-selection').isVisible(),false);
 await page.locator('#toggle-map-options').click();await page.locator('#fit-map').click();await page.locator('#close-map-options').click();
 const fitted=await diag();await page.mouse.move(800,500);await page.mouse.down();await page.mouse.move(880,530,{steps:5});await page.mouse.up();
 assert.notDeepEqual((await diag()).target,fitted.target);
 await page.setViewportSize({width:1024,height:850});
 assert.deepEqual(await page.locator('#map-canvas').boundingBox(),{x:0,y:0,width:1024,height:850});
 await page.screenshot({path:out+'/map-1024.png'});
 await page.locator('#toggle-map-options').click();await page.screenshot({path:out+'/map-options-1024.png'});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.keyboard.press('Escape');assert.equal(await page.locator('#map-options').isVisible(),false);
 assert.deepEqual(await(await page.request.get(base+'/atlas/api/bootstrap')).json(),before);assert.deepEqual(errors,[]);
 await writeFile(out+'/checks.json',JSON.stringify({passed:true,sourceUnchanged:true,checks:['edge-to-edge map','navigation expand/collapse/hide','tools hidden by default','utility layers','optional search','on-demand property dialog','pan','1600/1024 viewport'],errors},null,2));
 console.log('PASS: full viewport, hidden/collapsible navigation, optional tools and property dialog, source selection, utility layers, pan and responsive layout.');
}catch(error){throw error;}finally{await browser.close();}
